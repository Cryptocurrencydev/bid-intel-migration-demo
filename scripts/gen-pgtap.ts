// privacy-rules.yaml → supabase/tests/10_privacy_matrix.test.sql (+ a JSON manifest for the UI).
// One assertion per persona × probe, plus a "control" assertion per probe proving the fixture
// exists (run with RLS bypassed), so a deny can't pass just because the row is missing.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { loadSpec, expandAllow, type Spec } from "../lib/spec";

const spec: Spec = loadSpec(readFileSync("privacy-rules.yaml", "utf8"));
const personas = Object.keys(spec.personas);

const sub = (sql: string) =>
  sql.replace(/\{\{(\w+)\}\}/g, (_, k) => {
    const v = spec.fixtures[k];
    if (!v) throw new Error(`unknown fixture {{${k}}}`);
    return v;
  });

type Cell = { type: string; probe: string; persona: string; expect: "allow" | "deny"; desc: string };
const cells: Cell[] = [];
const controls: { type: string; probe: string; desc: string }[] = [];
const lines: string[] = [];
const allPolicies: string[] = [];

for (const [typeName, dt] of Object.entries(spec.data_types)) {
  allPolicies.push(...(dt.postgres?.policies ?? []));
  for (const [probeName, probe] of Object.entries(dt.probes ?? {})) {
    const allow = new Set(expandAllow(spec, probe.allow));
    for (const a of allow) if (!personas.includes(a)) throw new Error(`${typeName}.${probeName}: unknown persona ${a}`);
    const sql = sub(probe.sql).replace(/\$q\$/g, "");
    if (probe.control !== false) {
      const desc = `[${typeName}.${probeName}] control (RLS bypassed) → fixture present`;
      controls.push({ type: typeName, probe: probeName, desc });
      lines.push(`select is(tests.probe('service', '${probe.kind}', $q$${sql}$q$), 'allow', '${desc}');`);
    }
    for (const persona of personas) {
      const expect = allow.has(persona) ? "allow" : "deny";
      const desc = `[${typeName}.${probeName}] ${persona} → ${expect}`;
      cells.push({ type: typeName, probe: probeName, persona, expect, desc });
      const assertion = expect === "allow" ? `'allow'` : `'deny'`;
      lines.push(`select is(split_part(tests.probe('${persona}', '${probe.kind}', $q$${sql}$q$), ':', 1), ${assertion}, '${desc}');`);
    }
  }
}

const header = `-- GENERATED by scripts/gen-pgtap.ts from privacy-rules.yaml. Do not edit by hand.
-- ${cells.length} matrix cells (${personas.length} personas) + ${controls.length} controls + 3 coverage checks.
begin;
create extension if not exists pgtap with schema extensions;
set search_path = public, extensions;
select plan(${cells.length + controls.length + 3});

create schema tests;
grant usage on schema tests to anon, authenticated;

-- Runs p_sql as the persona inside a subtransaction that is always rolled back, so probes
-- never affect each other. Returns 'allow', or 'deny:<sqlstate>' for the error classes that
-- mean "blocked". Any other error (typo, missing column) re-raises and fails the run.
create function tests.probe(p_persona text, p_kind text, p_sql text) returns text
language plpgsql as $fn$
declare
  v_uid uuid;
  v_role text;
  v_n bigint;
  v_val text;
  v_allowed boolean;
begin
  if p_persona = 'anon' then
    v_role := 'anon';
  elsif p_persona = 'service' then
    v_role := null;
  else
    select id into v_uid from auth.users where email = p_persona || '@fixture.test';
    if v_uid is null then raise exception 'unknown persona %', p_persona; end if;
    v_role := 'authenticated';
  end if;
  begin
    if v_role is not null then
      perform set_config('request.jwt.claims', json_build_object('sub', v_uid, 'role', v_role)::text, true);
      perform set_config('role', v_role, true);
    end if;
    if p_kind = 'dml' then
      execute p_sql;
      get diagnostics v_n = row_count;
      v_allowed := v_n > 0;
    elsif p_kind = 'rows' then
      execute 'select count(*) from (' || p_sql || ') q' into v_n;
      v_allowed := v_n > 0;
    elsif p_kind in ('value', 'call') then
      execute 'select q.* from (' || p_sql || ') q limit 1' into v_val;
      v_allowed := v_val is not null;
    else
      raise exception 'unknown probe kind %', p_kind;
    end if;
    raise exception using errcode = 'P0099', message = case when v_allowed then 'allow' else 'deny:empty' end;
  exception
    when sqlstate 'P0099' then return sqlerrm;
    when insufficient_privilege then return 'deny:' || sqlstate;        -- 42501 grant / RLS with check
    when foreign_key_violation then return 'deny:' || sqlstate;         -- 23503 composite tenant FK
    when not_null_violation then return 'deny:' || sqlstate;            -- 23502 no tenant for anon
    when check_violation then return 'deny:' || sqlstate;               -- 23514
    when object_not_in_prerequisite_state then return 'deny:' || sqlstate; -- 55000 view not updatable
    when feature_not_supported then return 'deny:' || sqlstate;         -- 0A000 view not updatable
  end;
end $fn$;
grant execute on function tests.probe(text, text, text) to anon, authenticated;

-- Coverage: every policy in the database is declared in the YAML and vice versa.
select set_eq(
  $$select policyname::text from pg_policies
    where schemaname = 'public' or (schemaname = 'storage' and (policyname like 'report_files_%' or policyname like 'org_logos_%'))$$,
  array[${[...new Set(allPolicies)].map((p) => `'${p}'`).join(", ")}]::text[],
  'policies in the database == policies declared in privacy-rules.yaml'
);
select is(
  (select count(*)::int from pg_tables where schemaname = 'public' and not rowsecurity), 0,
  'RLS is enabled on every public table'
);
select is(
  (select count(*)::int from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname in ('public', 'private') and p.prosecdef and p.proconfig is null), 0,
  'every security definer function pins search_path'
);
`;

writeFileSync("supabase/tests/10_privacy_matrix.test.sql", `${header}\n${lines.join("\n")}\n\nselect * from finish();\nrollback;\n`);
mkdirSync("snapshot", { recursive: true });
writeFileSync(
  "snapshot/matrix-manifest.json",
  JSON.stringify({
    personas: spec.personas,
    groups: spec.groups,
    entitlements: spec.entitlements,
    data_types: Object.fromEntries(Object.entries(spec.data_types).map(([k, d]) => [k, {
      table: d.table, view: d.view ?? null, bubble_rules: d.bubble_rules, restricted_fields: d.restricted_fields ?? {}, postgres: d.postgres ?? {},
      probes: Object.fromEntries(Object.entries(d.probes ?? {}).map(([pn, pr]) => [pn, { kind: pr.kind, sql: sub(pr.sql), allow: expandAllow(spec, pr.allow), control: pr.control !== false }])),
    }])),
    cells, controls, policies: [...new Set(allPolicies)],
  }),
);
console.log(`wrote ${cells.length} cells, ${controls.length} controls, ${personas.length} personas`);
