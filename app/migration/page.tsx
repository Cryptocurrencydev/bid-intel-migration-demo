import { latestValidation } from "@/lib/ci";

export const revalidate = 300;

const yes = (b: boolean) => <span className={`badge ${b ? "allow" : "deny"}`}>{b ? "match" : "mismatch"}</span>;
const ms = (n: number) => (n >= 1000 ? `${(n / 1000).toFixed(1)} s` : `${n} ms`);

export default async function Migration() {
  const { report: V, source } = await latestValidation();
  const run = V.last_run;
  return (
    <>
      <h1>Migration validation report</h1>
      <p className="lead">
        Generated by <code>migration/validate.ts</code> after the migration runs twice in CI. It re-extracts everything from the (mock) Bubble Data API
        on its own instead of trusting the migrator's copy, then compares against Supabase.
      </p>
      <p className="small muted">Source: {source === "release" ? "latest green CI run on main (release asset ci-latest)" : "committed snapshot"}.</p>
      <div className="grid three">
        <div className="card"><div className="stat-label">Result</div><div className="stat" style={{ color: V.status === "pass" ? "var(--allow)" : "var(--deny)" }}>{String(V.status).toUpperCase()}</div><div className="small muted">{V.generated_at.slice(0, 16).replace("T", " ")} UTC</div></div>
        <div className="card"><div className="stat-label">Bubble records</div><div className="stat">{V.bubble_records.toLocaleString("en-US")}</div><div className="small muted">9 data types, {run ? run.files.total : "—"} files re-hosted</div></div>
        <div className="card"><div className="stat-label">Re-run (idempotency)</div><div className="stat">{V.idempotency.ok ? "0 changes" : "changed"}</div><div className="small muted">run #{V.idempotency.second_run}: +{V.idempotency.second_run_inserted} inserted, ~{V.idempotency.second_run_updated} updated, {V.idempotency.second_run_files_uploaded} files uploaded</div></div>
        {run && <div className="card"><div className="stat-label">Run timings</div><div className="stat">{ms(run.timings_ms.total)}</div><div className="small muted">extract {ms(run.timings_ms.extract)} · transform {ms(run.timings_ms.transform)} · load {ms(run.timings_ms.load)} · files {ms(run.timings_ms.files)}</div></div>}
      </div>

      <h2>Row counts</h2>
      <div className="scroll">
        <table>
          <thead><tr><th>Bubble type → table</th><th className="num">Bubble</th><th className="num">Supabase</th><th /></tr></thead>
          <tbody>
            {[...V.counts, ...V.list_fields_and_files].map((c: any) => (
              <tr key={c.type}><td>{c.type}</td><td className="num">{c.bubble.toLocaleString("en-US")}</td><td className="num">{c.supabase.toLocaleString("en-US")}</td><td>{yes(c.match)}</td></tr>
            ))}
          </tbody>
        </table>
      </div>

      <h2>Key-field checksums</h2>
      <div className="scroll">
        <table>
          <thead><tr><th>Type</th><th>Fields</th><th>Bubble md5</th><th>Supabase md5</th><th /></tr></thead>
          <tbody>
            {V.checksums.map((c: any) => (
              <tr key={c.type}><td>{c.type}</td><td className="small">{c.fields.join(", ")}</td><td><code>{c.bubble_md5.slice(0, 12)}</code></td><td><code>{c.supabase_md5.slice(0, 12)}</code></td><td>{yes(c.match)}</td></tr>
            ))}
          </tbody>
        </table>
      </div>

      <h2>Referential integrity</h2>
      <div className="scroll">
        <table>
          <thead><tr><th>Check</th><th className="num">Violations</th></tr></thead>
          <tbody>
            {V.integrity.map((i: any) => <tr key={i.check}><td>{i.check}</td><td className="num"><span className={`badge ${i.ok ? "allow" : "deny"}`}>{i.violations}</span></td></tr>)}
          </tbody>
        </table>
      </div>

      <div className="grid two" style={{ marginTop: "1.5rem" }}>
        <div className="card">
          <h3>Stripe customers ↔ organizations</h3>
          <ul className="small" style={{ paddingLeft: "1.1rem", margin: 0 }}>
            <li>{V.stripe.customers_in_export} customers in the Stripe export</li>
            <li>{V.stripe.matched_by_id_and_metadata} orgs matched by customer id and <code>metadata.bubble_org_id</code></li>
            <li>{V.stripe.backfilled_from_stripe_metadata} customer ids lost in Bubble, backfilled from Stripe metadata</li>
            <li>{V.stripe.subscribed_orgs_without_customer.length} subscribed orgs without a customer · {V.stripe.metadata_mismatch.length} metadata mismatches</li>
            <li>{V.stripe.stripe_customers_without_org.length} Stripe customers with no org (deleted in Bubble): {V.stripe.stripe_customers_without_org.map((c: any) => c.id).join(", ")}</li>
          </ul>
        </div>
        <div className="card">
          <h3>Users without email: {V.users_without_email.count}</h3>
          <p className="small muted">They're migrated as members without a login (passwordless auth needs an address) and flagged for customer success outreach.</p>
          <ul className="small" style={{ paddingLeft: "1.1rem", margin: 0 }}>
            {V.users_without_email.users.map((u: any) => <li key={u.bubble_id}>{u.name} <code>{u.bubble_id}</code></li>)}
          </ul>
        </div>
      </div>

      <h2>Issues carried forward ({V.issues.length})</h2>
      <p className="small muted">These are data problems Bubble allowed and Postgres doesn't. The migrator logs each one in <code>migration.issues</code> instead of silently dropping or keeping it.</p>
      <div className="scroll">
        <table>
          <thead><tr><th>Kind</th><th>Type</th><th>Bubble id</th><th>Detail</th></tr></thead>
          <tbody>{V.issues.map((i: any) => <tr key={i.kind + i.bubble_id}><td><span className="badge">{i.kind}</span></td><td>{i.bubble_type}</td><td><code>{i.bubble_id}</code></td><td className="small">{i.detail}</td></tr>)}</tbody>
        </table>
      </div>

      <h2>Random sample diffs: Bubble vs Supabase</h2>
      <p className="small muted">3 seeded random records per type. Bubble ids map to deterministic UUIDs (v5) and every mapping is kept in <code>migration.id_map</code>.</p>
      <div className="grid two">
        {V.samples.map((s: any) => (
          <div className="card tight" key={s.bubble_id}>
            <div className="spread"><strong>{s.type}</strong>{yes(s.match)}</div>
            <div className="small muted" style={{ overflowWrap: "anywhere" }}><code>{s.bubble_id}</code> → <code>{s.uuid}</code></div>
            <div className="diff" style={{ marginTop: ".4rem" }}>
              <div className="h">field</div><div className="h">Bubble</div><div className="h">Supabase</div><div className="h" />
              {s.fields.map((f: any) => (
                <div key={f.field} style={{ display: "contents" }}>
                  <div className="f"><code>{f.field}</code></div><div>{f.bubble || "—"}</div><div>{f.supabase || "—"}</div><div>{f.match ? "✓" : "✕"}</div>
                </div>
              ))}
            </div>
          </div>
        ))}
      </div>

      {run && (
        <>
          <h2>Last migration run (#{run.run})</h2>
          <div className="scroll">
            <table>
              <thead><tr><th>Table</th><th className="num">Rows</th><th className="num">Inserted</th><th className="num">Updated</th><th className="num">Unchanged</th><th className="num">Batches</th><th className="num">ms</th></tr></thead>
              <tbody>
                {Object.entries(run.load as Record<string, any>).map(([t, s]) => (
                  <tr key={t}><td>{t}</td><td className="num">{s.rows}</td><td className="num">{s.inserted}</td><td className="num">{s.updated}</td><td className="num">{s.unchanged}</td><td className="num">{s.batches}</td><td className="num">{s.ms}</td></tr>
                ))}
              </tbody>
            </table>
          </div>
        </>
      )}
      <p className="small" style={{ marginTop: "1.25rem" }}>
        Cutover and rollback runbook: <a href="https://github.com/Cryptocurrencydev/bid-intel-migration-demo/blob/main/MIGRATION.md">MIGRATION.md</a>
      </p>
    </>
  );
}
